DISPATCH_SOURCE = "control-plane-profile-update-dispatcher"
OPEN_TASK_STATUSES = ("pending", "running", "failed", "partial")
RECOMMENDATION_STAGE_MAP: dict[str, tuple[str, str]] = {
    "strengthen_stage_gate": ("review", "reviewer"),
    "clarification_upgrade_needed": ("clarify", "project-agent"),
    "parallelize_stage_candidate": ("implement", "backend-dev"),
    "stage_simplification_candidate": ("implement", "backend-dev"),
}
RECOMMENDATION_PRIORITY_MAP: dict[str, tuple[str, str]] = {
    "strengthen_stage_gate": ("high", "high"),
    "clarification_upgrade_needed": ("high", "high"),
    "parallelize_stage_candidate": ("medium", "low"),
    "stage_simplification_candidate": ("low", "low"),
}


def _normalize_review_payload(review_raw: Any) -> dict[str, Any]:
    """Normalize one profile-update dispatch input into the review report body."""

    if not isinstance(review_raw, dict):
        raise ValueError("optimization review payload must be a JSON object")
    nested_report = review_raw.get("report")
    if isinstance(nested_report, dict):
        return nested_report
    return review_raw


def load_control_plane_optimization_review_report(review_file: str | Path) -> dict[str, Any]:
    """Load one optimization-review report from disk.

    Args:
        review_file: JSON report path generated by `control_plane_optimization_review_runner.py`.

    Returns:
        dict[str, Any]: Normalized review report payload.

    Raises:
        FileNotFoundError: Raised when the report file does not exist.
        ValueError: Raised when the payload shape is invalid.
    """

    path = Path(review_file).expanduser()
    if not path.exists():
        raise FileNotFoundError(f"optimization review file does not exist: {path}")
    payload = json.loads(path.read_text(encoding="utf-8-sig"))
    report = _normalize_review_payload(payload)
    items = report.get("items", [])
    if not isinstance(items, list):
        raise ValueError("optimization review items must be a list")
    normalized_report = dict(report)
    normalized_report["items"] = [item for item in items if isinstance(item, dict)]
    return normalized_report


def _collect_open_change_ids(task_center: TaskCenter) -> set[str]:
    """Collect open workflow-profile-update change ids already present in task-center."""

    placeholders = ",".join("?" for _ in OPEN_TASK_STATUSES)
    rows = task_center.conn.execute(
        f"""
        SELECT change_id
        FROM tasks
        WHERE source = ?
          AND status IN ({placeholders})
        """,
        (DISPATCH_SOURCE, *OPEN_TASK_STATUSES),
    ).fetchall()
    return {str(row["change_id"] or "").strip() for row in rows if str(row["change_id"] or "").strip()}


def _resolve_execution_plan(review_item: dict[str, Any]) -> dict[str, str]:
    """Resolve execution stage and default assignee for one profile-update item."""

    recommendation_type = str(review_item.get("recommendation_type", "")).strip()
    stage_id, assignee = RECOMMENDATION_STAGE_MAP.get(recommendation_type, ("implement", "backend-dev"))
    return {"stage_id": stage_id, "assignee": assignee}


def _resolve_priority_and_risk(review_item: dict[str, Any]) -> tuple[str, str]:
    """Resolve task priority and risk level from the recommendation type."""

    recommendation_type = str(review_item.get("recommendation_type", "")).strip()
    return RECOMMENDATION_PRIORITY_MAP.get(recommendation_type, ("medium", "low"))


def _build_change_id(review_item: dict[str, Any]) -> str:
    """Build the stable task-center change id for one profile update task."""

    origin_change_id = str(review_item.get("change_id", "")).strip()
    origin_task_id = str(review_item.get("task_id", "")).strip()
    suffix = origin_change_id or origin_task_id or uuid.uuid4().hex[:12]
    return f"control-plane-profile-update:{suffix}"


def _build_task_payload(
    *,
    review_item: dict[str, Any],
    execution_workflow_profile: str,
    execution_workflow_channel: str,
    schedule_at: str,
) -> dict[str, Any]:
    """Build one task-center payload for a workflow profile update task."""

    execution_plan = _resolve_execution_plan(review_item)
    priority, risk_level = _resolve_priority_and_risk(review_item)
    capability_binding = resolve_task_capability_binding(
        execution_plan["assignee"],
        required_capabilities=[],
        required_skills=[],
        allowed_agents=[],
    )
    target_workflow_profile_id = str(review_item.get("target_workflow_profile_id", "")).strip()
    target_stage_id = str(review_item.get("target_stage_id", "")).strip()
    target_stage_label = str(review_item.get("target_stage_label", "")).strip() or target_stage_id or "unknown-stage"
    recommendation_type = str(review_item.get("recommendation_type", "")).strip()
    latest_agent_report_summary = str(review_item.get("latest_agent_report_summary", "")).strip()
    origin_task_id = str(review_item.get("task_id", "")).strip()
    origin_change_id = str(review_item.get("change_id", "")).strip()
    change_id = _build_change_id(review_item)

    requirement_lines = [
        f"[change_id:{change_id}]",
        f"[origin_task_id:{origin_task_id or 'unknown'}]",
        f"[origin_change_id:{origin_change_id or 'unknown'}]",
        "根据 optimization review 已通过项，修改对应 workflow profile / stage 配置。",
        f"- 目标 workflow：{target_workflow_profile_id or 'unknown-workflow'}",
        f"- 目标 stage：{target_stage_id or 'unknown-stage'} ({target_stage_label})",
        f"- 推荐类型：{recommendation_type or 'unknown-recommendation'}",
        f"- 上游执行摘要：{latest_agent_report_summary or '未提供'}",
    ]
    result_output = (
        "输出 workflow profile 级别的最小修改方案与实际变更，"
        "包含 stage manifest、gate/evidence/benchmark 影响说明和验证证据。"
    )
    acceptance = (
        "至少形成一项可验证的 profile 变更；不得破坏 selector、promotion、"
        "benchmark、cron 主链；需说明回滚方式或阻塞原因。"
    )
    observable_outputs = "workflow profile patch, stage contract update, benchmark evidence, task report"
    acceptance_thresholds = "至少 1 项 profile 变更进入可验证状态，并提供验证证据或明确阻塞原因"
    context_payload = {
        "dispatch_source": "control_plane_optimization_review",
        "origin_task_id": origin_task_id,
        "origin_change_id": origin_change_id,
        "target_workflow_profile_id": target_workflow_profile_id,
        "target_stage_id": target_stage_id,
        "target_stage_label": target_stage_label,
        "execution_workflow_profile_id": execution_workflow_profile,
        "execution_workflow_channel": execution_workflow_channel,
        "execution_stage_id": execution_plan["stage_id"],
        "review_item": review_item,
        "capability_binding": {
            "assignee": capability_binding["assignee"],
            "resolution_reason": capability_binding["resolution_reason"],
            "required_capabilities": capability_binding["required_capabilities"],
            "required_skills": capability_binding["required_skills"],
            "allowed_agents": capability_binding["allowed_agents"],
        },
    }
    selection_inputs = {
        "dispatch_source": "control_plane_optimization_review",
        "origin_task_id": origin_task_id,
        "origin_change_id": origin_change_id,
        "target_workflow_profile_id": target_workflow_profile_id,
        "target_stage_id": target_stage_id,
        "recommendation_type": recommendation_type,
        "execution_stage_id": execution_plan["stage_id"],
        "capability_binding": context_payload["capability_binding"],
    }
    title = f"{target_workflow_profile_id}/{target_stage_label} -> profile_update"

    return {
        "task_id": f"todo-control-plane-profile-update-{datetime.now().strftime('%Y%m%d%H%M%S')}-{uuid.uuid4().hex[:6]}",
        "pool": "todo",
        "task_type": "workflow_profile_update",
        "reason": f"[CONTROL_PLANE_PROFILE_UPDATE] {title}",
        "source": DISPATCH_SOURCE,
        "request_source": "ai",
        "priority": priority,
        "risk_level": risk_level,
        "assignee": capability_binding["assignee"] or execution_plan["assignee"],
        "required_capabilities": capability_binding["required_capabilities"],
        "required_skills": capability_binding["required_skills"],
        "allowed_agents": capability_binding["allowed_agents"],
        "status": "pending",
        "need_human_confirm": False,
        "human_confirmed": True,
        "change_id": change_id,
        "requirement": "\n".join(requirement_lines),
        "result_output": result_output,
        "acceptance": acceptance,
        "observable_outputs": observable_outputs,
        "acceptance_thresholds": acceptance_thresholds,
        "context_payload": context_payload,
        "scheduled_at": schedule_at,
        "workflow_profile_id": str(execution_workflow_profile or "").strip(),
        "workflow_channel": str(execution_workflow_channel or "").strip(),
        "selection_reason": "control_plane_profile_update_dispatcher",
        "selection_inputs": selection_inputs,
        "stage_id": execution_plan["stage_id"],
    }


def render_control_plane_profile_update_dispatch_markdown(dispatch: dict[str, Any]) -> str:
    """Render one Markdown summary for profile update dispatch."""

    lines = [
        "# OpenClaw Control Plane Profile Update Dispatcher",
        "",
        f"- 生成时间：{dispatch.get('generated_at', '')}",
        f"- 输入评审报告：{dispatch.get('review_file', '')}",
        f"- 执行 workflow：{dispatch.get('execution_workflow_profile', '')}@{dispatch.get('execution_workflow_channel', '')}",
        f"- 新建任务：{dispatch.get('created_count', 0)}",
        f"- 跳过任务：{dispatch.get('skipped_count', 0)}",
        "",
        "## 已创建任务",
    ]
    created = dispatch.get("created", [])
    if isinstance(created, list) and created:
        for item in created:
            if not isinstance(item, dict):
                continue
            lines.append(
                f"- {item.get('task_id', '')}: {item.get('recommendation_type', '')} -> "
                f"{item.get('target_workflow_profile_id', '')}/{item.get('target_stage_id', '')} "
                f"@ {item.get('assignee', '')}"
            )
    else:
        lines.append("- 本次未创建新的 profile update 任务")

    lines.extend(["", "## 已跳过任务"])
    skipped = dispatch.get("skipped", [])
    if isinstance(skipped, list) and skipped:
        for item in skipped:
            if not isinstance(item, dict):
                continue
            lines.append(
                f"- {item.get('origin_task_id', '')}: {item.get('recommendation_type', '')} -> "
                f"{item.get('target_workflow_profile_id', '')}/{item.get('target_stage_id', '')} / {item.get('reason', '')}"
            )
    else:
        lines.append("- 本次没有跳过项")
    return "\n".join(lines).rstrip() + "\n"


def dispatch_control_plane_profile_update_tasks(
    *,
    review_file: str | Path,
    task_db: str | Path,
    execution_workflow_profile: str,
    execution_workflow_channel: str,
    schedule_gap_minutes: int = 60,
) -> dict[str, Any]:
    """Dispatch ready optimization-review items into workflow profile update tasks.

    Args:
        review_file: Review report generated by `control_plane_optimization_review_runner.py`.
        task_db: Task-center SQLite path.
        execution_workflow_profile: Workflow profile used to execute the update task.
        execution_workflow_channel: Workflow channel used to execute the update task.
        schedule_gap_minutes: Gap between created tasks in minutes.

    Returns:
        dict[str, Any]: Structured dispatch summary including created and skipped items.
    """

    report = load_control_plane_optimization_review_report(review_file)
    items = report.get("items", [])
    task_center = TaskCenter(Path(task_db).expanduser())
    task_center.init_schema()
    created: list[dict[str, Any]] = []
    skipped: list[dict[str, Any]] = []
    open_change_ids = _collect_open_change_ids(task_center)
    normalized_gap = max(0, int(schedule_gap_minutes or 0))

    try:
        for index, review_item in enumerate(items if isinstance(items, list) else []):
            if not isinstance(review_item, dict):
                continue
            origin_task_id = str(review_item.get("task_id", "")).strip()
            recommendation_type = str(review_item.get("recommendation_type", "")).strip()
            target_workflow_profile_id = str(review_item.get("target_workflow_profile_id", "")).strip()
            target_stage_id = str(review_item.get("target_stage_id", "")).strip()
            if not bool(review_item.get("ready_for_profile_update", False)):
                skipped.append(
                    {
                        "origin_task_id": origin_task_id,
                        "recommendation_type": recommendation_type,
                        "target_workflow_profile_id": target_workflow_profile_id,
                        "target_stage_id": target_stage_id,
                        "reason": "not_ready_for_profile_update",
                    }
                )
                continue

            schedule_at = (
                datetime.now(tz=timezone.utc) + timedelta(minutes=normalized_gap * len(created))
            ).replace(microsecond=0).isoformat()
            task_payload = _build_task_payload(
                review_item=review_item,
                execution_workflow_profile=execution_workflow_profile,
                execution_workflow_channel=execution_workflow_channel,
                schedule_at=schedule_at,
            )
            change_id = str(task_payload.get("change_id", "")).strip()
            if change_id in open_change_ids:
                skipped.append(
                    {
                        "origin_task_id": origin_task_id,
                        "recommendation_type": recommendation_type,
                        "target_workflow_profile_id": target_workflow_profile_id,
                        "target_stage_id": target_stage_id,
                        "reason": "duplicate_open_change_id",
                    }
                )
                continue

            task_center.create_task(task_payload, actor="control-plane-profile-update-dispatcher")
            open_change_ids.add(change_id)
            created.append(
                {
                    "task_id": str(task_payload["task_id"]),
                    "task_type": str(task_payload["task_type"]),
                    "change_id": change_id,
                    "origin_task_id": origin_task_id,
                    "origin_change_id": str(review_item.get("change_id", "")).strip(),
                    "recommendation_type": recommendation_type,
                    "target_workflow_profile_id": target_workflow_profile_id,
                    "target_stage_id": target_stage_id,
                    "assignee": str(task_payload["assignee"]),
                    "stage_id": str(task_payload["stage_id"]),
                    "scheduled_at": schedule_at,
                }
            )
    finally:
        task_center.close()

    summary = report.get("summary", {}) if isinstance(report.get("summary", {}), dict) else {}
    dispatch = {
        "generated_at": utc_now_iso(),
        "review_file": str(Path(review_file).expanduser()),
        "task_db": str(Path(task_db).expanduser()),
        "execution_workflow_profile": str(execution_workflow_profile or "").strip(),
        "execution_workflow_channel": str(execution_workflow_channel or "").strip(),
        "created_count": len(created),
        "skipped_count": len(skipped),
        "created": created,
        "skipped": skipped,
        "source_summary": {
            "task_count": int(summary.get("task_count", 0) or 0),
            "ready_for_profile_update_count": int(summary.get("ready_for_profile_update_count", 0) or 0),
            "blocked_count": int(summary.get("blocked_count", 0) or 0),
            "pending_count": int(summary.get("pending_count", 0) or 0),
        },
    }
    dispatch["markdown"] = render_control_plane_profile_update_dispatch_markdown(dispatch)
    return dispatch


def build_parser() -> argparse.ArgumentParser:
    """Build the CLI parser."""

    parser = argparse.ArgumentParser(description="Dispatch ready optimization review items into profile update tasks.")
    parser.add_argument("--review-file", required=True)
    parser.add_argument("--task-db", required=True)
    parser.add_argument("--execution-workflow-profile", required=True)
    parser.add_argument("--execution-workflow-channel", required=True)
    parser.add_argument("--schedule-gap-minutes", default="60")
    parser.add_argument("--json-output", default="")
    parser.add_argument("--markdown-output", default="")
    parser.add_argument("--emit-json", action="store_true")
    return parser


def main(argv: list[str] | None = None) -> dict[str, Any]:
    """Run the CLI and return the dispatch payload."""

    parser = build_parser()
    args = parser.parse_args(argv)
    dispatch = dispatch_control_plane_profile_update_tasks(
        review_file=str(args.review_file).strip(),
        task_db=str(args.task_db).strip(),
        execution_workflow_profile=str(args.execution_workflow_profile).strip(),
        execution_workflow_channel=str(args.execution_workflow_channel).strip(),
        schedule_gap_minutes=max(0, int(args.schedule_gap_minutes or 60)),
    )
    payload = {"dispatch": dispatch}
    if str(args.json_output or "").strip():
        write_json_atomic(
            Path(str(args.json_output).strip()).expanduser(),
            payload,
            ensure_ascii=False,
            indent=2,
            file_mode=0o644,
            dir_mode=0o755,
        )
    if str(args.markdown_output or "").strip():
        atomic_write_text(
            Path(str(args.markdown_output).strip()).expanduser(),
            dispatch["markdown"],
            encoding="utf-8",
            newline="\n",
            file_mode=0o644,
            dir_mode=0o755,
        )
    if bool(args.emit_json):
        print(json.dumps(payload, ensure_ascii=False))
    else:
        print(dispatch["markdown"])
    return payload


if __name__ == "__main__":
    main()
